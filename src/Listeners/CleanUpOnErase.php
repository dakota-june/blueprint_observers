<?php

declare(strict_types=1);

namespace Dakotajune\Blueclues\Listeners;

use Dakotajune\Blueclues\Support\BlueprintFile;
use Dakotajune\Blueclues\Support\ManifestStore;
use Dakotajune\Blueclues\Support\NoticeBag;
use Dakotajune\Blueclues\Support\ObservedByInjector;
use Dakotajune\Blueclues\Support\ObserverClassEditor;
use Illuminate\Console\Events\CommandStarting;
use Illuminate\Filesystem\Filesystem;

/**
 * `blueprint:erase` deletes every file listed under `created` in `.blueprint`. Left alone that would
 * destroy developer methods inside a generated observer and cannot revert edits to existing models.
 * So, just before it starts, we:
 *
 *  1. strip the #[ObservedBy] attributes (and imports) we added to models;
 *  2. strip the `@generated blueclues` methods from each observer we touched;
 *  3. if an observer still holds developer content (or we did not create it), take it off erase's
 *     delete list by editing `.blueprint` (backed up first), so erase leaves it alone.
 *
 * Observers with nothing left of the developer's are left on the list for erase to delete as normal.
 */
final class CleanUpOnErase
{
    public function __construct(
        private readonly Filesystem $files,
        private readonly ObservedByInjector $injector,
        private readonly ObserverClassEditor $editor,
        private readonly ManifestStore $manifests,
        private readonly BlueprintFile $blueprintFile,
        private readonly NoticeBag $notices,
    ) {}

    public function handle(CommandStarting $event): void
    {
        if ($event->command !== 'blueprint:erase') {
            return;
        }

        $manifest = $this->manifests->load();

        if ($manifest->isEmpty()) {
            return;
        }

        foreach ($manifest->models() as $modelPath => $observers) {
            $absolute = base_path($modelPath);

            if (! $this->files->exists($absolute)) {
                continue; // e.g. the model itself was generated by Blueprint and erase will delete it
            }

            $original = $source = $this->files->get($absolute);

            foreach ($observers as $observerFqcn => $meta) {
                $source = $this->injector->remove($source, $meta['model'], $observerFqcn, $meta['imports']);
            }

            if ($source !== $original) {
                $this->files->put($absolute, $source);
            }
        }

        $protect = [];

        foreach ($manifest->observers() as $path => $meta) {
            $absolute = base_path($path);

            if (! $this->files->exists($absolute)) {
                continue;
            }

            $original = $this->files->get($absolute);
            $stripped = $this->editor->stripGenerated($original, $meta['class']);

            if ($stripped !== $original) {
                $this->files->put($absolute, $stripped);
            }

            if (! $meta['created'] || $this->editor->hasDeveloperContent($stripped, $meta['class'])) {
                $protect[] = $path;
                $this->notices->add("{$path} still contains your code, so it was kept; only the generated methods were removed.");
            }
        }

        $backup = $this->blueprintFile->protect($protect);

        if ($backup !== null) {
            $this->notices->add('Edited .blueprint so erase skips the files above. The original is saved as ' . basename($backup) . '.');
        }

        $this->manifests->delete();
    }
}
