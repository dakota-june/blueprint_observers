<?php

declare(strict_types=1);

namespace Dakotajune\Blueclues\Listeners;

use Dakotajune\Blueclues\Support\ManifestStore;
use Dakotajune\Blueclues\Support\ObservedByInjector;
use Illuminate\Console\Events\CommandStarting;
use Illuminate\Filesystem\Filesystem;

/**
 * `blueprint:erase` deletes the files listed under `created` in `.blueprint`, which covers the
 * generated observers. It cannot revert edits to existing models, so just before it runs we strip the
 * #[ObservedBy] attributes (and imports) that blueclues added, using the `.blueclues` manifest.
 */
final class RestoreModelsOnErase
{
    public function __construct(
        private readonly Filesystem $files,
        private readonly ObservedByInjector $injector,
        private readonly ManifestStore $manifests,
    ) {}

    public function handle(CommandStarting $event): void
    {
        if ($event->command !== 'blueprint:erase') {
            return;
        }

        foreach ($this->manifests->load()->entries() as $modelPath => $observers) {
            $absolute = base_path($modelPath);

            if (! $this->files->exists($absolute)) {
                continue; // already deleted, e.g. the model itself was generated by Blueprint
            }

            $original = $source = $this->files->get($absolute);

            foreach ($observers as $observerFqcn => $meta) {
                $source = $this->injector->remove($source, $meta['model'], $observerFqcn, $meta['imports']);
            }

            if ($source !== $original) {
                $this->files->put($absolute, $source);
            }
        }

        $this->manifests->delete();
    }
}
